// Original 65C816 homebrew fixture: green screen, P1 B makes it red, P2 B blue.
export function makeSnesFixture() {
  const rom = new Uint8Array(32768), code = [], labels = new Map(), refs = [];
  const emit = (...bytes) => code.push(...bytes), label = n => labels.set(n, code.length);
  const branch = (op, name) => { emit(op, 0); refs.push([code.length - 1, name]); };
  emit(0x78,0x18,0xfb,0xc2,0x38,0xa9,0,0,0x5b,0xa2,0xff,0x1f,0x9a,0xe2,0x20);
  emit(0xa9,0x80,0x8d,0,0x21,0xa9,0,0x8d,0x21,0x21,0xa9,0xe0,0x8d,0x22,0x21,0xa9,3,0x8d,0x22,0x21);
  emit(0xa9,0x0f,0x8d,0,0x21,0xa9,1,0x8d,0,0x42);
  label('wait'); emit(0xad,0x12,0x42); branch(0x10,'wait');
  label('joy'); emit(0xad,0x12,0x42,0x29,1); branch(0xd0,'joy');
  emit(0xa9,0,0x8d,0x21,0x21,0xad,0x19,0x42,0x29,0x80); branch(0xd0,'red');
  emit(0xad,0x1b,0x42,0x29,0x80); branch(0xd0,'blue');
  emit(0xa9,0xe0,0x8d,0x22,0x21,0xa9,3); branch(0x80,'write');
  label('red'); emit(0xa9,31,0x8d,0x22,0x21,0xa9,0); branch(0x80,'write');
  label('blue'); emit(0xa9,0,0x8d,0x22,0x21,0xa9,0x7c);
  label('write'); emit(0x8d,0x22,0x21);
  label('end'); emit(0xad,0x12,0x42); branch(0x30,'end'); branch(0x80,'wait');
  for (const [at, name] of refs) { const d = labels.get(name) - at - 1; if (d < -128 || d > 127) throw new Error('branch'); code[at] = d & 255; }
  rom.set(code); rom.set(new TextEncoder().encode('RETRO ROOM SNES TEST  '),0x7fc0);
  rom[0x7fd5]=0x20; rom[0x7fd6]=0; rom[0x7fd7]=5; rom[0x7fd9]=1; rom[0x7fda]=0x33;
  rom[0x7ffc]=0; rom[0x7ffd]=0x80;
  return rom;
}
